"""Единый источник таблицы единиц для трёх реализаций проверки ответа.

Правильный ответ на задание по физике — это величина: число и единица. Единицы
разбирает Python (`content_src/quantities.py`) при авторской сборке банка, но на
устройстве тот же ответ проверяет JavaScript (`webapp/core.js`) и Kotlin
(`AnswerChecker.kt`). Чтобы таблицы не разъезжались, она **генерируется** из
Python и вставляется в оба приложения:

* `webapp/core.js` — блок между метками `/* >>> units:generated */` и
  `/* <<< units:generated */`;
* `android/app/src/main/java/by/ziv/ctphysics/UnitTable.kt` — константа с тем же
  JSON.

`tools/build_content.py` вызывает :func:`render_javascript` и
:func:`render_kotlin`, а `tests/test_content.py` проверяет, что вложенные копии
совпадают с Python.

Запуск вручную (посмотреть таблицу)::

    python3 tools/unit_table.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "content_src") not in sys.path:
    sys.path.insert(0, str(ROOT / "content_src"))

JS_MARKER_BEGIN = "/* >>> units:generated */"
JS_MARKER_END = "/* <<< units:generated */"


def _table() -> dict:
    import quantities as quantities_module

    seen: dict[int, dict] = {}
    for unit in quantities_module._SYMBOLS.values():
        if id(unit) in seen:
            continue
        seen[id(unit)] = {
            "s": unit.symbol,
            "ru": unit.ru,
            "en": unit.en,
            "dim": list(unit.dim.exps),
            "f": _float_text(unit.factor),
            "fexact": f"{unit.factor.numerator}/{unit.factor.denominator}",
            "o": float(unit.offset),
            "p": bool(unit.prefixable),
            "a": sorted({unit.symbol, unit.ru, unit.en, *unit.aliases}),
        }
    units = sorted(seen.values(), key=lambda item: item["s"])
    prefixes = [{"ru": ru, "la": la, "f": _float_text(factor)}
                for ru, la, factor in quantities_module.PREFIXES]
    return {"units": units, "prefixes": prefixes}


def _float_text(value) -> str:
    """Число в записи, которую одинаково читают Python, JS и Kotlin.

    Полная точность double: множители вроде 20265/152 нельзя округлять, иначе
    «мм рт. ст.» в трёх реализациях получит разные значения.
    """
    number = float(value)
    if number == int(number) and abs(number) < 1e16:
        return str(int(number))
    return repr(number)


def payload() -> dict:
    """Таблица единиц и приставок (единый источник для JS, Kotlin и тестов)."""
    return _table()


def unit_names() -> list[str]:
    """Все обозначения и синонимы единиц — для тестов контента."""
    names: list[str] = []
    for unit in _table()["units"]:
        for name in unit["a"]:
            if name not in names:
                names.append(name)
    return names


def _compact(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def render_javascript() -> str:
    """Строка с `A.UNITS = [...]` и `A.PREFIXES = [...]` (в одну строку)."""
    table = _table()
    units = json.dumps(table["units"], ensure_ascii=False, sort_keys=True,
                       separators=(",", ":"))
    prefixes = json.dumps(table["prefixes"], ensure_ascii=False, sort_keys=True,
                          separators=(",", ":"))
    return f"  A.UNITS = {units};\n  A.PREFIXES = {prefixes};"


def render_kotlin() -> str:
    """Kotlin-файл с таблицей единиц в виде JSON-строки."""
    return f"""package by.ziv.ctphysics

// GENERATED by tools/build_content.py from content_src/quantities.py - do not edit.
// The same table is embedded in webapp/core.js and in the Python authoring code;
// tests/answer_parity.js and the Android unit tests compare all three.
internal object UnitTable {{

    /** JSON: {{units: [...], prefixes: [...]}} — см. tools/unit_table.py. */
    const val JSON = \"\"\"{_compact(_table())}\"\"\"
}}
"""


def apply_javascript(source: str) -> str:
    """Вставить сгенерированный блок в исходник `webapp/core.js`."""
    begin = source.index(JS_MARKER_BEGIN)
    end = source.index(JS_MARKER_END)
    head = source[:begin + len(JS_MARKER_BEGIN)]
    tail = source[end:]
    return f"{head}\n{render_javascript()}\n{tail}"


#: Эталонные векторы разбора единиц: Python → JS → Kotlin.
UNIT_VECTORS_PATH = ROOT / "tests" / "unit_vectors.json"

GOOD_UNITS = [
    "м", "m", "кг", "kg", "с", "s", "А", "ампер", "К", "кельвин", "моль", "кд",
    "г", "грамм", "т", "мин", "ч", "сут", "л", "L", "эВ", "а.е.м.", "°C",
    "Н", "ньютон", "Дж", "Вт", "Па", "Гц", "Кл", "В", "Ом", "Ω", "Ф", "Тл", "Вб", "Гн",
    "м/с", "м/с²", "км/ч", "г/см³", "кВт·ч", "мм рт. ст.",
    "кг·м/с²", "kg·m/s^2", "Дж/кг", "Дж/(кг·К)", "Н·м²/Кл²", "кПа", "МПа", "мН",
    "нКл", "мкКл", "мкФ", "кОм", "МОм", "кДж", "МДж", "кВт", "мВт", "мА", "мка",
    "кГц", "МГц", "мТл", "дптр", "1", "Дж·с", "кг·м", "кг·м²/с²",
    "кг/м³", "Н/м", "кг/с²", "1/м", "1/с", "Кл/кг", "В/м", "А·с", "м²", "м³", "см³", "мм²",
]

BAD_UNITS = ["", "  ", "фунт", "год", "5*м", "%", "кг^^2", "м+с", "лL", "безразмерная"]


def unit_vectors() -> dict:
    """Разобранные эталоны: то, что обязаны повторить JS и Kotlin."""
    import quantities as quantities_module

    cases = []
    for text in GOOD_UNITS:
        unit = quantities_module.parse_unit(text)
        cases.append({
            "input": text,
            "ok": True,
            "dim": list(unit.dim.exps),
            "factor": _float_text(unit.factor),
            "offset": float(unit.offset),
        })
    for text in BAD_UNITS:
        try:
            quantities_module.parse_unit(text)
        except quantities_module.QuantityError:
            cases.append({"input": text, "ok": False})
        else:
            raise AssertionError(f"единица {text!r} не должна разбираться")
    return {"note": "Эталон разбора единиц: Python → JS → Kotlin", "units": cases}


def write_unit_vectors(path: Path = UNIT_VECTORS_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(unit_vectors(), ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8")
    return path


def unit_vectors_text() -> str:
    return json.dumps(unit_vectors(), ensure_ascii=False, indent=1) + "\n"


if __name__ == "__main__":
    print(json.dumps(payload(), ensure_ascii=False, indent=1, sort_keys=True))
